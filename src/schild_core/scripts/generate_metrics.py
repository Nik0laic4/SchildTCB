#!/usr/bin/env python3
"""Generate the canonical SPARK-metrics block into every public artifact.

Reads ``obj/proof/metrics.json`` (written by prove_kernel.sh) plus the current
git commit, then rewrites the ``<!-- METRICS:START --> ... <!-- METRICS:END -->``
region in each artifact so the published numbers can never drift from the
machine-generated canon. This is the single taxonomy (auditor / endorsement
feedback §2): one source of truth, numbers generated with an explicit commit
marker.

Usage (from src/schild_core):
    python3 scripts/generate_metrics.py
"""
import json
import os
import subprocess
import sys
from datetime import date

# src/schild_core — the metrics.json lives here, artifacts are ../../<name>.
ROOT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPO_ROOT = os.path.abspath(os.path.join(ROOT_DIR, "..", ".."))

MARKER_START = "<!-- METRICS:START"
MARKER_END = "<!-- METRICS:END -->"

# artifact path (relative to repo root) -> language
ARTIFACTS = {
    "README.md": "en",
    "README.ru.md": "ru",
    "docs/methodology/textbook_en.md": "en",
    "docs/methodology/textbook_ru.md": "ru",
    "docs/technical/ASSURANCE.md": "en",
    "docs/technical/ASSURANCE.ru.md": "ru",
    "docs/ARTICLE.md": "en",
}

_EN = {
    "swept": "swept",
    "in_proof": "in proof",
    "proved": "proved",
    "skipped": "skipped",
    "no_output": "no-output",
    "scaffold": "scaffold excluded",
    "unproved": "unproved VCs",
    "accounting": (
        "Accounting: `swept` = all modules; `in_proof` = `swept` − "
        "`scaffold_excluded`; `proved + skipped + no_output + not_proved` = "
        "`in_proof`. Source: `obj/proof/metrics.json`."
    ),
}
_RU = {
    "swept": "прогнано",
    "in_proof": "в proof-наборе",
    "proved": "доказано",
    "skipped": "skipped",
    "no_output": "no-output",
    "scaffold": "scaffold исключено",
    "unproved": "непроверенных VC",
    "accounting": (
        "Схема учёта: `swept` = все модули; `in_proof` = `swept` − "
        "`scaffold_excluded`; `proved + skipped + no_output + not_proved` = "
        "`in_proof`. Источник: `obj/proof/metrics.json`."
    ),
}


def commit_sha():
    out = subprocess.check_output(
        ["git", "rev-parse", "--short", "HEAD"], text=True
    )
    return out.strip()


def tier_a_metric():
    """Tier-A coverage (review #7): On subprograms vs total, source-level.

    Counts procedure/function declarations in the Tier-A units; a unit whose
    body declares SPARK_Mode => Off is counted as Off (the documented trusted
    seams: syscall shim, boot manager, drivers). Approximates the requested
    'X subprograms On / Y total' — the gnatprove invocation emits text only,
    not the per-subprogram XML, so this is a cheap deterministic count."""
    import re
    allow = [
        "schild_sel4_syscall", "schild_root_task", "schild_boot_manager",
        "schild_audit_logger", "schild_mls_policy", "schild_cap_space",
        "schild_process_manager", "schild_fs_server",
    ]
    sub_re = re.compile(r"^\s*(procedure|function)\s+[A-Za-z0-9_]+", re.M)
    off_re = re.compile(
        r"SPARK_Mode\s*(?:=>|:)\s*Off|SPARK_Mode\s*\(\s*Off\s*\)", re.I)
    roots = [
        os.path.join(ROOT_DIR, "src"),
        os.path.join(ROOT_DIR, "tools", "sel4", "src"),
    ]
    on_subs = total = 0
    for root in roots:
        for dirpath, _, files in os.walk(root):
            for f in files:
                if f.endswith((".ads", ".adb")):
                    base = f[:-4]
                    if any(base == a or base.startswith(a + "-") for a in allow):
                        path = os.path.join(dirpath, f)
                        with open(path, encoding="utf-8", errors="replace") as fh:
                            txt = fh.read()
                        n = len(sub_re.findall(txt))
                        total += n
                        if not off_re.search(txt):
                            on_subs += n
    return on_subs, total


def render(metrics, sha, lang):
    t = _EN if lang == "en" else _RU
    swept = metrics["swept"]
    in_proof = metrics["in_proof"]
    proved = metrics["proved"]
    skipped = metrics["skipped"]
    no_output = metrics["no_output"]
    not_proved = metrics["not_proved"]
    scaffold = metrics["scaffold_excluded"]
    header = (
        f"{MARKER_START} (generated by scripts/generate_metrics.py — do not edit) -->"
    )
    line = (
        f"**SPARK metrics** (commit `{sha}`, {date.today().isoformat()}): "
        f"**{swept} {t['swept']}** · **{in_proof} {t['in_proof']}** "
        f"({proved} {t['proved']} · {skipped} {t['skipped']} · "
        f"{no_output} {t['no_output']}) · **{scaffold} {t['scaffold']}** · "
        f"**{not_proved} {t['unproved']}**."
    )
    tier_on, tier_total = tier_a_metric()
    tier_line = (
        f"**Tier A**: **{tier_on} subprograms On / {tier_total} total** "
        f"({tier_total - tier_on} Off — trusted seams: syscall shim, drivers)."
    )
    return f"{header}\n{line}\n{tier_line}\n\n{t['accounting']}\n{MARKER_END}"


def inject(path, block):
    with open(path, encoding="utf-8") as f:
        text = f.read()
    start = text.find(MARKER_START)
    end = text.find(MARKER_END)
    if start != -1 and end != -1:
        end += len(MARKER_END)
        text = text[:start] + block + text[end:]
    else:
        text = text.rstrip() + "\n\n" + block + "\n"
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


def main():
    metrics_path = os.path.join(ROOT_DIR, "obj", "proof", "metrics.json")
    with open(metrics_path, encoding="utf-8") as f:
        metrics = json.load(f)
    sha = commit_sha()
    for artifact, lang in ARTIFACTS.items():
        block = render(metrics, sha, lang)
        inject(os.path.join(REPO_ROOT, artifact), block)
        print(f"updated {artifact}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
