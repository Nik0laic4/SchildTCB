def to_bytes(rows):
    return [int(r, 2) for r in rows]

def main():
    font = {}
    for name, d in (("DIGITS", DIGITS), ("PUNCT", PUNCT), ("UPPER", UPPER), ("LOWER", LOWER)):
        for ch, rows in d.items():
            font[ord(ch)] = to_bytes(rows)
    default = [0x00,0x00,0x00,0x00,0xFF,0x81,0x81,0x81,0x81,0x81,0x81,0xFF,0x00,0x00,0x00,0x00]
    print("/* Generated by tools/gen_font8x16.py — do not edit. */")
    print("static const unsigned char schild_font8x16[95][16] = {")
    for code in range(0x20, 0x7F):
        rows = font.get(code, default)
        if len(rows) == 8:
            rows = [0,0,0,0] + rows + [0,0,0,0]
        rowstr = ",".join("0x%02X" % r for r in rows)
        ch = chr(code)
        label = ch if code not in (0x27, 0x5C) else ("\\'" if code == 0x27 else "\\\\")
        print("    { %s }, /* 0x%02X %s */" % (rowstr, code, label))
    print("};")

if __name__ == "__main__":
    main()

